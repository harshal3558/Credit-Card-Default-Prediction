import os
import sys
from src.CCDP.logger import logging
from src.CCDP.exception import CustomException
import pandas as pd

from sklearn.model_selection import train_test_split
from dataclasses import dataclass

# for reading sql data
from src.CCDP.utils import read_sql_data

@dataclass
class DataIngestionConfig:
    etl_data_path: str = os.path.join('etl_pipeline', 'include', 'transformed_credit_card_default.csv')
    train_data_path: str = os.path.join('artifacts', 'train.csv')
    test_data_path: str = os.path.join('artifacts', 'test.csv')
    raw_data_path: str = os.path.join('artifacts', 'raw.csv')

class DataIngestion:
    def __init__(self):
        self.ingestion_config = DataIngestionConfig()

    def initiate_data_ingestion(self, run_etl_if_missing: bool = True):
        try:
            etl_path = self.ingestion_config.etl_data_path

            # If ETL transformed output does not exist, trigger the standalone ETL pipeline
            if not os.path.exists(etl_path) and run_etl_if_missing:
                logging.info(f"ETL dataset not found at {etl_path}. Invoking ETL pipeline runner...")
                from etl_pipeline.main import run_standalone_etl
                run_standalone_etl()

            if os.path.exists(etl_path):
                logging.info(f"Loading transformed dataset generated by ETL pipeline from: {etl_path}")
                df = pd.read_csv(etl_path)
            else:
                fallback_path = os.path.join('notebook/data', 'raw.csv')
                logging.warning(f"ETL dataset not found at {etl_path}. Falling back to raw file: {fallback_path}")
                df = pd.read_csv(fallback_path)

            os.makedirs(os.path.dirname(self.ingestion_config.train_data_path), exist_ok=True)

            # Persist raw/curated snapshot in artifacts
            df.to_csv(self.ingestion_config.raw_data_path, index=False, header=True)

            logging.info("Performing train-test split (80-20, random_state=42)")
            train_set, test_set = train_test_split(df, test_size=0.2, random_state=42)

            train_set.to_csv(self.ingestion_config.train_data_path, index=False, header=True)
            test_set.to_csv(self.ingestion_config.test_data_path, index=False, header=True)

            logging.info("Data Ingestion from ETL output is completed successfully")

            return (
                self.ingestion_config.train_data_path,
                self.ingestion_config.test_data_path
            )

        except Exception as e:
            raise CustomException(e, sys)
